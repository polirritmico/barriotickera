-- APLICAR SCRIPT EN EL CONTENEDOR Y ESQUEMA DEL APLICATIVO
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = TICKETERA_APP;

--------------------------------------------------
--- Tabla BITACORA_ENTRADAS                     ---
--- (el "cuaderno" donde se anota quien crea,  ---
---  actualiza o borra entradas y cuando)      ---
--------------------------------------------------

-- Docker corre este script en cada arranque: si la tabla ya existe
-- (ORA-00955) se ignora el error en vez de fallar.
DECLARE
    e_tabla_ya_existe EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_tabla_ya_existe, -955);
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE BITACORA_ENTRADAS (
            id_bitacora  NUMBER GENERATED BY DEFAULT AS IDENTITY,
            operacion    VARCHAR2(20)  NOT NULL,
            usuario      VARCHAR2(128) NOT NULL,
            fecha        TIMESTAMP     NOT NULL,
            CONSTRAINT pk_bitacora_entradas
                PRIMARY KEY (id_bitacora),
            CONSTRAINT ck_bitacora_operacion
                CHECK (operacion IN (''CREAR'', ''ACTUALIZAR'', ''BORRAR''))
        )';
EXCEPTION
    WHEN e_tabla_ya_existe THEN
        NULL;
END;
/


--------------------------------------------------
--- Trigger: bitacora de operaciones sobre     ---
--- ENTRADAS                                   ---
--- Sentencia · AFTER INSERT/UPDATE/DELETE     ---
--------------------------------------------------

-- SIN "FOR EACH ROW": se ejecuta UNA vez por instruccion,
-- sin importar cuantas entradas toque.
CREATE OR REPLACE TRIGGER trg_bitacora_entradas
AFTER INSERT OR UPDATE OR DELETE ON entradas
DECLARE
    v_operacion  bitacora_entradas.operacion%TYPE;
BEGIN
    -- QUE OPERACION DESPERTO AL TRIGGER
    IF INSERTING THEN
        v_operacion := 'CREAR';
    ELSIF UPDATING THEN
        v_operacion := 'ACTUALIZAR';
    ELSIF DELETING THEN
        v_operacion := 'BORRAR';
    END IF;

    -- SE ANOTA EN LA BITACORA: QUE, QUIEN Y CUANDO
    INSERT INTO bitacora_entradas (operacion, usuario, fecha)
    VALUES (v_operacion, USER, SYSTIMESTAMP);
END trg_bitacora_entradas;
/

SHOW ERRORS TRIGGER trg_bitacora_entradas;
